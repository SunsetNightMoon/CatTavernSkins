# Read md file
md_path = 'G:/Skin2.catnight.top/minecraft-skin-server-plan3/frontend/src/pages/Admin/admin-translation-keys.md'
with open(md_path, 'r', encoding='utf-8') as f:
    content = f.read()

# Parse sections: section_name -> {key_without_admin_prefix: sch_translation}
sections_sch = {}
current_section = None
for line in content.split('\n'):
    line = line.strip()
    if not line:
        continue
    m = re.match(r'## admin\.(\w+)', line)
    if m:
        current_section = m.group(1)  # dashboard, users, skins, etc.
        sections_sch[current_section] = {}
    elif line.startswith('- '):
        kv = line[2:].strip()
        # Match both admin.* and common.* keys
        m2 = re.match(r'(admin\.\S+)\s+-\s+(.*)', kv)
        if m2:
            full_key = m2.group(1)
            value = m2.group(2).strip()
            # Remove 'admin.' prefix to get the key name for JSON
            json_key = full_key.replace('admin.', '', 1)
            if current_section:
                sections_sch[current_section][json_key] = value
        else:
            # Maybe common.* keys
            m3 = re.match(r'(common\.\S+)\s+-\s+(.*)', kv)
            if m3:
                full_key = m3.group(1)
                value = m3.group(2).strip()
                json_key = full_key.replace('common.', '', 1)
                # Store common.* keys in 'common' sub-object under admin
                if 'common' not in sections_sch:
                    sections_sch['common'] = {}
                sections_sch['common'][json_key] = value

print(f'Parsed {len(sections_sch)} sections')
total = sum(len(v) for v in sections_sch.values())
print(f'Total keys: {total}')

# Build admin object for SCH (simplified Chinese)
admin_sch = {}
for section_name, keys in sections_sch.items():
    admin_sch[section_name] = keys

