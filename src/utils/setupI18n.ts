export function t(key: string, lang: string = 'SCH', vars?: Record<string, string>): string {
  const msg = messages[lang]?.[key] || messages['SCH']?.[key] || key;
  if (!vars) return msg;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replace(new RegExp(`{{${k}}}`, 'g'), v),
    msg
  );
}

export function getLang(req: { headers: Record<string, any> }): string {
  const lang = req.headers['x-language'] || req.headers['X-Language'];
  if (lang && messages[lang]) return lang;
  return 'SCH';
}
